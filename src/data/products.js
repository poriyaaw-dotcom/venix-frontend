// Helper to convert English numbers to Farsi (FIXED: All 10 digits are now present)
export const toFarsiNumber = (num) => {
  const farsiDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return num.toString().replace(/\d/g, (x) => farsiDigits[x]);
};

// Helper to format price with commas
export const formatPrice = (price) => {
  return toFarsiNumber(price.toLocaleString('en-US'));
};